/** Recorrido real de interfaz, respuesta perdida, exportación privada y supresión. */
import { spawnSync } from 'node:child_process'
import { readFileSync,writeFileSync } from 'node:fs'
async function main() {
  const playwrightPath = '/srv/LogiQD/llenamos/.claude/pw/node_modules/playwright/index.mjs'
  const { chromium } = await import(playwrightPath)
  const browser = await chromium.launch({ headless:true,executablePath:'/home/gery/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome',args:['--no-sandbox'] })
  try {
    const context = await browser.newContext({ viewport:{ width:1440,height:1100 },deviceScaleFactor:2,acceptDownloads:true })
    const page = await context.newPage()
    const errors:string[] = []
    page.on('pageerror',(e:Error) => errors.push(e.message))
    page.on('response',(r:{ url():string;status():number }) => { if (r.url().includes('5012') && r.status() >= 400) console.log('Respuesta local',r.status(),new URL(r.url()).pathname) })
    await page.goto('http://localhost:3011/entrar')
    await page.getByLabel('Correo',{ exact:true }).fill('propietario@lumbre.test',{ timeout:60000 })
    await page.getByLabel('Contraseña',{ exact:true }).fill('Llenamos2026!')
    await page.getByRole('button',{ name:'Entrar',exact:true }).click()
    await page.waitForURL('**/panel**',{ timeout:60000 })
    await page.goto('http://localhost:3011/panel/privacidad')
    await page.getByText('Aún no hay solicitudes',{ exact:true }).waitFor({ timeout:60000 })
    await page.getByRole('combobox',{ name:'Cliente',exact:true }).click()
    await page.getByRole('option',{ name:/Celia Demo privacidad/ }).click()
    await page.getByLabel('Referencia de la evidencia',{ exact:true }).fill('demo-presencial')
    await page.getByLabel('Versión de la política',{ exact:true }).fill('demo-2026.1')
    await page.getByRole('combobox',{ name:'Decisión de la persona' }).click()
    await page.getByRole('option',{ name:'Da su permiso',exact:true }).click()
    await page.getByRole('button',{ name:'Registrar decisión',exact:true }).click()
    await page.getByText(/Decisión registrada/).waitFor({ timeout:30000 })
    await page.getByRole('combobox',{ name:'Decisión de la persona' }).click()
    await page.getByRole('option',{ name:'Retira el permiso',exact:true }).click()
    await page.getByRole('button',{ name:'Registrar decisión',exact:true }).click()
    await page.getByText(/Decisión registrada/).waitFor({ timeout:30000 })
    await page.getByLabel('Motivo de la solicitud',{ exact:true }).fill('Ejercicio de acceso con datos sintéticos')
    let lost = false,lostDone:() => void = () => {}
    const lostHandled = new Promise<void>(resolve => { lostDone = resolve })
    await page.route('**/solicitarPrivacidad',async (route:{ request():{ method():string };fetch():Promise<unknown>;fulfill(options:{ status:number;contentType:string;body:string }):Promise<void>;continue():Promise<void> }) => {
      if (!lost && route.request().method() === 'POST') { lost=true;await route.fetch();await route.fulfill({ status:503,contentType:'application/json',body:JSON.stringify({ error:{ message:'Respuesta perdida',status:'UNAVAILABLE' } }) });lostDone() } else await route.continue()
    })
    await page.getByRole('button',{ name:'Registrar solicitud',exact:true }).click()
    await lostHandled
    await page.getByRole('alert').filter({ hasText:/perdida|internal|unavailable|conexi/i }).first().waitFor({ timeout:30000 }).catch(() => undefined)
    await page.unroute('**/solicitarPrivacidad')
    await page.getByRole('button',{ name:'Registrar solicitud',exact:true }).click()
    await page.getByText(/Pendiente de verificar/).waitFor({ timeout:30000 })
    if (await page.getByText(/Pendiente de verificar/).count() !== 1) throw new Error('Se duplicó la solicitud al perder la respuesta.')
    await page.screenshot({ path:'docs/diseno/capturas/copias-rgpd/01-solicitud-escritorio.png',fullPage:true })
    await page.getByRole('button',{ name:'Verificar identidad',exact:true }).click()
    await page.getByText(/^● Identidad verificada/).waitFor({ timeout:30000 })
    function worker() { const result = spawnSync('node_modules/.bin/tsx',['scripts/privacidad-local.ts','procesar','demo-lumbre'],{ env:process.env,encoding:'utf8' });if (result.status) throw new Error(result.stderr);console.log(result.stdout.trim()) }
    worker()
    await page.getByRole('button',{ name:'Actualizar',exact:true }).click()
    await page.getByRole('button',{ name:'Descargar datos',exact:true }).waitFor({ timeout:30000 })
    await page.screenshot({ path:'docs/diseno/capturas/copias-rgpd/02-exportacion-lista.png',fullPage:true })
    const [download] = await Promise.all([page.waitForEvent('download'),page.getByRole('button',{ name:'Descargar datos',exact:true }).click()])
    const bytes = readFileSync(await download.path(),'utf8')
    if (!bytes.includes('Celia Demo privacidad') || bytes.includes('enlace-demo-privacidad')) throw new Error('Exportación incompleta o con secretos.')
    const used = await context.request.get(download.url())
    if (used.status() !== 403) throw new Error('El enlace se puede reutilizar.')
    await page.getByRole('combobox',{ name:'Qué solicita',exact:true }).click()
    await page.getByRole('option',{ name:'Borrar o anonimizar sus datos',exact:true }).click()
    await page.getByLabel('Motivo de la solicitud',{ exact:true }).fill('Ejercicio de supresión con datos sintéticos')
    await page.getByRole('button',{ name:'Registrar solicitud',exact:true }).click()
    await page.screenshot({ path:'docs/diseno/capturas/copias-rgpd/03-confirmar-borrado.png',fullPage:true })
    await page.getByRole('button',{ name:'Registrar solicitud de borrado',exact:true }).click()
    await page.getByRole('button',{ name:'Verificar identidad',exact:true }).waitFor({ timeout:30000 })
    await page.getByRole('button',{ name:'Verificar identidad',exact:true }).click()
    await page.getByText(/^● Identidad verificada/).waitFor({ timeout:30000 })
    worker()
    await page.getByRole('button',{ name:'Actualizar',exact:true }).click()
    await page.getByText('Ficha suprimida o fuera de la agenda cargada',{ exact:true }).first().waitFor({ timeout:30000 })
    await page.screenshot({ path:'docs/diseno/capturas/copias-rgpd/04-borrado-terminado.png',fullPage:true })
    await page.setViewportSize({ width:390,height:844 })
    await page.screenshot({ path:'docs/diseno/capturas/copias-rgpd/05-privacidad-movil.png',fullPage:true })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
    if (overflow || errors.length) throw new Error(JSON.stringify({ overflow,errors }))
    await context.storageState({ path:'/tmp/copias-browser-state.json',indexedDB:true })
    writeFileSync('docs/diseno/capturas/copias-rgpd/navegador.json',JSON.stringify({ at:new Date().toISOString(),viewportDesktop:[1440,1100],viewportMobile:[390,844],scale:2,lostResponseDeduplicated:lost,exportContainsCustomer:true,exportTokenOmitted:true,downloadSecondUseStatus:used.status(),mobileOverflow:overflow,browserErrors:errors },null,2)+'\n')
    console.log('Navegador: consentimiento, baja, respuesta perdida sin duplicar, exportación, enlace de un uso y borrado verificados.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error);process.exitCode=1 })
