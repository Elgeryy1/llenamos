export type MenuUiKey = keyof (typeof ui)["es"]
/** Las claves de los tres idiomas son las mismas: si falta una, esto no compila. */
export const MENU_UI_TEXT: Record<Language, Record<MenuUiKey, string>> = ui

/** Un texto de la interfaz con sus huecos rellenos: `menuUi("es", "pickupAt", { time: "21:30" })`. */
export function menuUi(language: Language, key: MenuUiKey, vars: Readonly<Record<string, string | number>> = {}): string {
  return MENU_UI_TEXT[language][key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

