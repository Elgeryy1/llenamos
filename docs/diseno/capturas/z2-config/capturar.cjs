    await foto(mobile.p, 'plano-movil')
    const suelo = mobile.p.getByRole('group', { name: 'Plano de Sala' })
    await suelo.scrollIntoViewIfNeeded()
    const scroller = suelo.locator('..')
    await scroller.evaluate(e => { e.scrollLeft = 0 })
    const rect = await scroller.boundingBox()
    const cd = await mobile.p.context().newCDPSession(mobile.p)
    const x = rect.x + rect.width - 30, y = rect.y + 165
    await cd.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
    for (let i = 1; i <= 8; i++) await cd.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - i * 15, y }] })
    await cd.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await pausa(mobile.p)
    assert.ok(await scroller.evaluate(e => e.scrollLeft) > 0, 'Deslizar el suelo recorre el plano')
    await cd.detach()
    await scroller.evaluate(e => { e.scrollLeft = 0 })
    const antes = await mesa(mobile.p).getAttribute('aria-label')
    await toqueArrastrado(mobile.p, mesa(mobile.p), 20, 14)
    assert.notEqual(await mesa(mobile.p).getAttribute('aria-label'), antes)
    await mobile.p.getByRole('button', { name: 'Descartar', exact: true }).click()
    await mesa(mobile.p).tap()
    const anchoMovil = await mobile.p.getByLabel('Ancho', { exact: true }).inputValue()
    await toqueArrastrado(mobile.p, mobile.p.getByTitle('Arrastra para cambiar el tamaño'), 15, 12)
    assert.notEqual(await mobile.p.getByLabel('Ancho', { exact: true }).inputValue(), anchoMovil)
    await mobile.p.getByLabel('Ancho', { exact: true }).scrollIntoViewIfNeeded()
    await foto(mobile.p, 'plano-inspector-movil')
    await mobile.p.getByRole('button', { name: 'Descartar', exact: true }).click()
    await abrir(mobile.p, 'horarios')
    await foto(mobile.p, 'horarios-movil')
    await mobile.p.locator('#semana').scrollIntoViewIfNeeded()
    await foto(mobile.p, 'horarios-turnos-movil')
    await abrir(mobile.p, 'compartir')
    await foto(mobile.p, 'compartir-movil')
    await mobile.p.getByLabel('Tipo de código').getByRole('radio', { name: 'Incrustado', exact: true }).tap()
    await mobile.p.locator('#widget').scrollIntoViewIfNeeded()
    await foto(mobile.p, 'compartir-widget-movil')
    resultado.push('Móvil táctil: arrastre y tamaño con eventos táctiles reales; capturas sin desborde a 390 px. Tableta: inspector y plano a 1180 px')
    await mobile.c.close()

    const manager = await entrar(b, 'encargado')
    for (const ruta of ['plano', 'horarios', 'compartir']) await abrir(manager.p, ruta)
    await abrir(manager.p, 'horarios')
    const campo = manager.p.getByLabel('Nombre del turno 1 del lunes', { exact: true })
