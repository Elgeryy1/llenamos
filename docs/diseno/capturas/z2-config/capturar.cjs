    const { c, p } = await entrar(b, 'propietario')
    await abrir(p, 'plano')
    await foto(p, 'plano-escritorio')
    const original = await mesa(p).getAttribute('aria-label')
    const box = await mesa(p).boundingBox()
    await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await p.mouse.down()
    await p.mouse.move(box.x + box.width / 2 + 24, box.y + box.height / 2 + 15, { steps: 6 })
    await p.mouse.up()
    assert.notEqual(await mesa(p).getAttribute('aria-label'), original)
    await p.getByRole('button', { name: 'Descartar', exact: true }).click()
    assert.equal(await mesa(p).getAttribute('aria-label'), original)
    await mesa(p).click()
    const ancho = await p.getByLabel('Ancho', { exact: true }).inputValue()
    const asa = p.getByTitle('Arrastra para cambiar el tamaño')
    const a = await asa.boundingBox()
    await p.mouse.move(a.x + a.width / 2, a.y + a.height / 2)
    await p.mouse.down()
    await p.mouse.move(a.x + a.width / 2 + 20, a.y + a.height / 2 + 12, { steps: 6 })
    await p.mouse.up()
    assert.notEqual(await p.getByLabel('Ancho', { exact: true }).inputValue(), ancho)
    await p.getByRole('button', { name: 'Descartar', exact: true }).click()
    await mesa(p).focus()
    await p.keyboard.press('ArrowRight')
    const movida = await mesa(p).getAttribute('aria-label')
    await guardarPlano(p)
    await abrir(p, 'plano')
    assert.equal(await mesa(p).getAttribute('aria-label'), movida)
    await mesa(p).focus()
    await p.keyboard.press('ArrowLeft')
    await guardarPlano(p)
    await abrir(p, 'plano')
    assert.equal(await mesa(p).getAttribute('aria-label'), original)
    resultado.push('Propietario: arrastre, redimensionado, teclado, descarte y guardado del plano persistente')

    await p.getByLabel('Nombre de la zona nueva').fill('Reservado de prueba')
    await p.getByRole('button', { name: 'Añadir zona', exact: true }).click()
    await p.getByRole('button', { name: 'Redonda', exact: true }).click()
    assert.equal(await p.getByLabel('Forma de la mesa').getByRole('radio', { name: 'Redonda', exact: true }).getAttribute('data-state'), 'on')
    await p.getByRole('button', { name: 'Descartar', exact: true }).click()
    resultado.push('Plano: alta de zona y mesa redonda en borrador, descartadas sin guardar')

    await abrir(p, 'horarios')
    await foto(p, 'horarios-escritorio')
    const llegada = p.getByLabel('Primera llegada, Comida del lunes', { exact: true })
    await llegada.fill('29:99')
    assert.equal(await llegada.getAttribute('aria-invalid'), 'true')
    assert.equal(await p.getByRole('button', { name: 'Guardar configuración', exact: true }).isDisabled(), true)
    await p.getByRole('button', { name: 'Descartar', exact: true }).click()
    await p.locator('#semana').getByRole('button', { name: 'Copiar', exact: true }).first().click()
    const pop = p.getByRole('dialog')
    await pop.getByLabel('martes', { exact: true }).check()
    await pop.getByRole('button', { name: 'Copiar', exact: true }).click()
    assert.equal(await p.getByLabel('Nombre del turno 1 del martes', { exact: true }).inputValue(), 'Comida')
    // Copiar días iguales puede no dejar cambios pendientes.
    if (await p.getByRole('button', { name: 'Descartar', exact: true }).isVisible()) await p.getByRole('button', { name: 'Descartar', exact: true }).click()
    await p.getByLabel('Fecha del día especial nuevo').fill('2026-12-24')
    await p.getByRole('button', { name: 'Añadir día especial', exact: true }).click()
    await p.getByLabel('Tipo del día 2026-12-24').getByRole('radio', { name: 'Otro horario', exact: true }).click()
    await p.getByLabel('Nombre del turno 1 del 2026-12-24', { exact: true }).waitFor()
    await p.getByRole('button', { name: 'Descartar', exact: true }).click()
    resultado.push('Horarios: validación, guardado bloqueado ante error, copia de día y horario especial')
    await p.locator('#duracion').scrollIntoViewIfNeeded()
    await foto(p, 'horarios-capacidad-escritorio')

    await p.getByRole('switch', { name: 'Aceptar reservas por la web', exact: false }).click()
    await guardarHorarios(p)
    await abrir(p, 'compartir')
    await p.getByText('Reservas no disponibles', { exact: true }).waitFor()
    await foto(p, 'compartir-cerrado-escritorio')
    await abrir(p, 'horarios')
    await p.getByRole('switch', { name: 'Aceptar reservas por la web', exact: false }).click()
    await guardarHorarios(p)
    await abrir(p, 'compartir')
    await p.getByText('Página publicada', { exact: true }).waitFor()
    await foto(p, 'compartir-escritorio')
    await p.getByRole('button', { name: 'Copiar enlace', exact: true }).click()
    assert.equal(await p.evaluate(() => navigator.clipboard.readText()), `${base}/r/taberna-lumbre`)
    await p.getByLabel('Tipo de código').getByRole('radio', { name: 'Incrustado', exact: true }).click()
    assert.match(await p.locator('#widget code').innerText(), /<iframe src="http:\/\/localhost:3014\/widget\/taberna-lumbre"/)
    await p.getByRole('button', { name: 'Copiar código', exact: true }).click()
    assert.match(await p.evaluate(() => navigator.clipboard.readText()), /<iframe /)
    const nueva = p.waitForEvent('popup')
    await p.getByRole('link', { name: 'Abrir', exact: true }).click()
    const publica = await nueva
    await publica.waitForURL(`${base}/r/taberna-lumbre`)
    await publica.getByRole('heading', { name: /Taberna Lumbre/ }).first().waitFor()
    await publica.close()
    resultado.push('Compartir: estado abierto y cerrado tras guardar en Functions, copia de enlace e iframe y apertura de página pública')

    await abrir(p, 'muestra')
    await p.locator('#m-configuracion').scrollIntoViewIfNeeded()
    await foto(p, 'muestra-configuracion')
    await c.close()

    const tablet = await entrar(b, 'propietario', { width: 1180, height: 820 }, true)
    await abrir(tablet.p, 'plano')
    await mesa(tablet.p).tap()
    await foto(tablet.p, 'plano-tableta')
    await tablet.c.close()

    const mobile = await entrar(b, 'propietario', { width: 390, height: 844 }, true)
