// Acciones y permisos de Z1 con Auth, Firestore y Functions locales.
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base='http://localhost:3011'
async function main() {
 const browser=await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? {executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH} : {})
 const errors=[]
 try {
  const context=await browser.newContext({viewport:{width:1440,height:900},timezoneId:'Europe/Madrid'})
  const page=await context.newPage();page.setDefaultTimeout(15000)
  page.on('pageerror',e=>errors.push(e.message))
  async function login(role,email) {
   await page.goto(base+'/entrar')
   await page.getByRole('button',{name:`Entrar como ${role} con ${email}`}).click()
   await page.waitForURL('**/panel')
   await page.getByRole('heading',{level:1}).waitFor()
  }
  async function logout() {
   await page.goto(base+'/logiqd')
   await page.getByRole('button',{name:'Salir',exact:true}).click()
   await page.waitForURL('**/entrar')
   await page.getByRole('button',{name:'Entrar',exact:true}).waitFor()
   assert.equal(await page.getByLabel('Correo',{exact:true}).inputValue(),'')
  }
  async function navigate(route,title) {
   await page.goto(base+route)
   await page.getByRole('heading',{level:1,name:title}).waitFor()
  }
  await login('propietario','propietario@lumbre.test')
  await navigate('/panel/ajustes','La identidad de tu restaurante')
  const color=page.getByLabel('Color de marca',{exact:true})
  const initial=await color.inputValue()
  await color.fill('no es un color')
  await page.getByRole('button',{name:'Guardar cambios'}).click()
  assert.equal(await color.getAttribute('aria-invalid'),'true')
  await color.fill('#dd9955')
  await page.getByRole('button',{name:'Guardar cambios'}).click()
  await page.getByText('Cambios guardados.',{exact:true}).waitFor()
  await page.reload()
  await color.waitFor();assert.equal(await color.inputValue(),'#dd9955')
  await color.fill(initial)
  await page.getByRole('button',{name:'Guardar cambios'}).click()
  await page.getByText('Cambios guardados.',{exact:true}).waitFor()
  console.log('Propietario: validación, guardado real, recarga y restauración de ajustes.')
  await navigate('/panel/equipo','6 personas en el equipo')
  async function roleChange(next) {
   const select=page.getByRole('combobox',{name:'Rol de Lucía Ferrer'})
   await select.click()
   await page.getByRole('option',{name:next,exact:true}).click()
   await page.getByText('Rol cambiado',{exact:true}).waitFor()
   await page.waitForTimeout(400)
   assert.equal((await select.innerText()).trim(),next)
  }
  await roleChange('Barra')
  await roleChange('Camarero')
  await page.getByRole('button',{name:'Más acciones para Lucía Ferrer'}).click()
  await page.getByRole('menuitem',{name:'Desactivar a Lucía Ferrer'}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Desactivar',exact:true}).click()
  await page.getByRole('heading',{name:'5 personas en el equipo'}).waitFor()
  await page.getByRole('button',{name:'Invitar',exact:true}).click()
  const dialog=page.getByRole('dialog')
  await dialog.getByLabel('Nombre',{exact:true}).fill('Lucía Ferrer')
  await dialog.getByLabel('Correo',{exact:true}).fill('camarera@lumbre.test')
  await dialog.getByLabel('Contraseña temporal',{exact:true}).fill('Llenamos2026!')
  await dialog.getByRole('button',{name:'Invitar',exact:true}).click()
  await page.getByRole('heading',{name:'6 personas en el equipo'}).waitFor()
  console.log('Propietario: cambio de rol, desactivación y reactivación mediante invitación.')
  await navigate('/panel/actividad','Cada cambio tiene su historia')
  await page.getByText(/Marta Soler/).first().waitFor()
  await page.getByRole('button',{name:'Ver más',exact:true}).click()
  await page.waitForTimeout(500)
  assert(await page.getByRole('listitem').count()>=30)
  console.log('Actividad: autor y paginación.')
  await navigate('/panel/mensajes',/mensajes|mensaje/)
  await page.getByRole('button',{name:/Abrir .* para/}).first().waitFor()
  const search=page.getByRole('searchbox',{name:'Buscar mensajes'})
  await search.fill('noexistez1')
  await page.getByText('Ningún mensaje coincide',{exact:true}).waitFor()
  await search.clear()
  await page.getByRole('combobox',{name:'Ordenar mensajes'}).selectOption('guest')
  await page.getByRole('combobox',{name:'Canal',exact:true}).selectOption('email')
  await page.getByText('Ningún mensaje coincide',{exact:true}).waitFor()
  await page.getByRole('combobox',{name:'Canal',exact:true}).selectOption('all')
  const row=page.getByRole('button',{name:/Abrir .* para/}).first()
  await row.focus();await page.keyboard.press('Enter')
  await page.getByRole('dialog').waitFor()
  await page.getByText('Tal cual le llega al cliente',{exact:true}).waitFor()
  // El detalle se cierra cuando Next oculta la ruta.
  await page.goto(base+'/panel')
  await page.goto(base+'/panel/mensajes')
  assert.equal(await page.getByRole('dialog').count(),0)
  const processed=page.waitForResponse(r=>r.url().includes('procesarMensajesPendientes') && r.request().method()==='POST')
  await page.getByRole('button',{name:'Procesar pendientes',exact:true}).click()
  assert.equal((await processed).status(),200)
  console.log('Mensajes: búsqueda, filtros, orden, detalle con teclado, cierre al navegar y procesado local.')
  await logout()
  await login('encargado','encargada@lumbre.test')
  await navigate('/panel/ajustes','La identidad de tu restaurante')
  await navigate('/panel/equipo','6 personas en el equipo')
  assert.equal(await page.getByRole('combobox',{name:'Rol de Marta Soler'}).count(),0)
  await page.getByRole('button',{name:'Invitar',exact:true}).click()
  assert.equal(await page.getByRole('dialog').getByRole('option',{name:'Propietario',exact:true}).count(),0)
  await page.keyboard.press('Escape')
  await navigate('/panel/actividad','Cada cambio tiene su historia')
  await navigate('/panel/mensajes',/mensajes|mensaje/)
  console.log('Encargado: acceso a Z1 y restricciones sobre propietarios conservadas.')
  await logout()
  await login('camarero','camarero@lumbre.test')
  await page.getByRole('heading',{name:/mesas listas/}).waitFor()
  for(const [route,what] of [['ajustes','los ajustes'],['equipo','el equipo'],['actividad','la actividad'],['mensajes','los mensajes']]) {
   await page.goto(`${base}/panel/${route}`)
   await page.getByText(`Tu rol no puede ver ${what}`,{exact:true}).waitFor()
  }
  await page.goto(base+'/logiqd')
  await page.getByText('Esta página es solo para el equipo de LogiQD',{exact:true}).waitFor()
  await logout()
  await login('camarero','camarera@lumbre.test')
  console.log('Camarero: inicio accesible, páginas restringidas protegidas y cuenta reactivada operativa.')
  await logout()
  await page.getByLabel('Correo',{exact:true}).fill('equipo@logiqd.test')
  await page.getByLabel('Contraseña',{exact:true}).fill('Llenamos2026!')
  await page.getByRole('button',{name:'Entrar',exact:true}).click()
  await page.waitForURL('**/panel')
  await navigate('/logiqd','1 restaurante en Llenamos')
  for(const choice of ['Encendido','Según el plan']) {
   await page.getByRole('button',{name:'Cambiar plan',exact:true}).locator('visible=true').click()
   const repite=page.getByRole('radiogroup',{name:'Repite: según el plan, encendido o apagado'})
   await repite.getByRole('radio',{name:choice,exact:true}).click()
   const saved=page.waitForResponse(r=>r.url().includes('cambiarPlan') && r.request().method()==='POST')
   await page.getByRole('button',{name:'Guardar plan',exact:true}).click()
   assert.equal((await saved).status(),200)
   await page.getByRole('dialog').waitFor({state:'hidden'})
  }
  console.log('LogiQD: cambio real de un módulo y restauración del plan original.')
  assert.deepEqual(errors,[])
  console.log('Comprobación Z1 completa sin errores de ejecución.')
 } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
