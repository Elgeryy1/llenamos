// Capturas reales y recorridos contra la web y los emuladores de la fila 2.
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const routes = JSON.parse(fs.readFileSync('/tmp/llenamos-z4-rutas.json', 'utf8'))
const base = 'http://localhost:3012'
const checks = []
const errors = []
const screenshots = []
let currentSize = ''

async function photo(page, name) {
  await page.addStyleTag({content:'nextjs-portal { display: none; }'})
  await page.evaluate(() => document.fonts.ready)
  await page.waitForTimeout(200)
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Sin desborde: ${name} ${currentSize}`)
  const file = `${name}-${currentSize}.png`
  await page.screenshot({ path: path.join(__dirname, file), animations: 'disabled' })
  screenshots.push(file)
  console.log(file)
}
async function open(page, route, text) {
  await page.goto(base + route)
  if (text) await page.getByRole('heading', {name:text, exact:true}).waitFor()
  await page.evaluate(()=>window.scrollTo(0,0))
}
async function booking(page, slug) {
  await open(page, `/r/${slug}`, 'Personas')
  // Elegimos mañana para que todas las horas sigan dentro del plazo al repetir el guion.
  await page.locator('#sec-dia').locator('..').getByRole('radio').nth(1).click()
  await page.waitForFunction(() => document.querySelector('#sec-hora')?.parentElement?.querySelector('button:not(:disabled)'))
  const available = page.locator('#sec-hora').locator('..').locator('button:not(:disabled)').first()
  await available.click()
}
async function details(page, phone, errorName = 'datos-errores') {
  await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('heading',{name:'Tus datos',exact:true}).waitFor()
  await page.getByRole('button',{name:'Confirmar reserva',exact:true}).click()
  await page.getByText('Escribe tu nombre.',{exact:true}).waitFor()
  await photo(page,errorName)
  await page.getByRole('textbox',{name:'Nombre',exact:true}).fill('Clara Vidal')
  await page.getByRole('textbox',{name:'Teléfono',exact:true}).fill(phone)
  await page.getByRole('textbox',{name:'Correo (opcional)',exact:true}).fill('clara@example.test')
  await page.getByRole('textbox',{name:'Algo que debamos saber (opcional)',exact:true}).fill('Una trona, por favor.')
  await page.getByRole('checkbox').check()
}
async function main() {
  const browser = await chromium.launch(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})
  try {
    for (const [size, viewport] of Object.entries({escritorio:{width:1440,height:900},movil:{width:390,height:844}})) {
      currentSize=size
      const phone = '+346' + String(Date.now()).slice(-8)
      const context=await browser.newContext({viewport,deviceScaleFactor:2,timezoneId:'Europe/Madrid',isMobile:size==='movil',hasTouch:size==='movil'})
      context.on('page',p=>p.on('pageerror',e=>errors.push(e.message)))
      // Se bloquea cualquier proveedor real, además de usar el proyecto demo.
      await context.route(/https:\/\/(api\.stripe\.com|checkout\.stripe\.com|api\.resend\.com|graph\.facebook\.com)\//, route=>{errors.push('Intento de proveedor externo');route.abort()})
      const page=await context.newPage()
      await booking(page,'taberna-lumbre')
      await page.evaluate(()=>window.scrollTo(0,0))
      await photo(page,'reservar')
      await page.getByRole('heading',{name:'Hora',exact:true}).scrollIntoViewIfNeeded()
      await photo(page,'horas')
      await page.getByRole('button',{name:'Otra fecha',exact:true}).click()
      await page.getByRole('dialog').waitFor()
      await photo(page,'calendario')
      await page.keyboard.press('Escape')
      await page.getByRole('dialog').waitFor({state:'hidden'})
      await details(page,phone)
      await page.evaluate(()=>window.scrollTo(0,0))
      await photo(page,'datos')
      await page.getByRole('button',{name:'Confirmar reserva',exact:true}).click()
      await page.waitForURL('**/reserva/**')
      await page.getByRole('heading',{name:'Tienes mesa, Clara',exact:true}).waitFor()
      await photo(page,'confirmada')
      const created = page.url()
      // Descargar y copiar siguen usando las acciones existentes.
      const download=page.waitForEvent('download')
      await page.getByRole('button',{name:'Añadir al calendario',exact:true}).click()
      assert.match((await download).suggestedFilename(), /^reserva-.+\.ics$/)
      await page.getByRole('button',{name:'Copiar enlace',exact:true}).click()
      await page.getByRole('button',{name:'Enlace copiado',exact:true}).waitFor()
      await page.getByRole('button',{name:'Cancelar reserva',exact:true}).click()
      await page.getByRole('dialog').waitFor()
      assert.equal(await page.getByRole('button',{name:'No, mantenerla',exact:true}).evaluate(el=>el===document.activeElement),true)
      await photo(page,'cancelar')
      await page.getByRole('button',{name:'Sí, cancelar',exact:true}).click()
      await page.getByRole('heading',{name:'Reserva cancelada',exact:true}).waitFor()
      await photo(page,'cancelada')
      checks.push(`${size}: reserva web real, calendario ICS, copia, foco seguro y cancelación; ${new URL(created).pathname}`)

      await open(page,routes.pending,'Reserva recibida, Clara')
      await photo(page,'pendiente')
      await open(page,routes.inactive,'Reserva pendiente')
      assert.equal(await page.getByRole('button',{name:'Pagar la señal',exact:true}).count(),0)
      await photo(page,'senal-no-configurada')
      await open(page,routes.deposit,'Falta pagar la señal')
      await photo(page,'senal-pendiente')
      await page.getByRole('button',{name:'Pagar la señal',exact:true}).click()
      await page.getByText('Los pagos de señal no están configurados. Contacta con el restaurante.',{exact:true}).waitFor()
      await photo(page,'senal-aviso')
      checks.push(`${size}: la señal inactiva no ofrece pagar; la señal requerida informa sin contactar con Stripe`)
      await open(page,routes.confirmed,'Tienes mesa, Clara')
      await page.getByRole('button',{name:'Cancelar reserva',exact:true}).click()
      await page.getByRole('dialog').waitFor()
      const brand=await page.getByRole('button',{name:'No, mantenerla',exact:true}).evaluate(el=>getComputedStyle(el).getPropertyValue('--primary').trim())
      assert.equal(brand,'#8fc7a0')
      await photo(page,'cancelar-marca')
      await page.keyboard.press('Escape')
      checks.push(`${size}: marca verde heredada también en el diálogo de cancelación`)

      await booking(page,routes.slug)
      await page.getByRole('button',{name:'Apúntate a la lista de espera',exact:true}).click()
      await page.getByRole('heading',{name:'Lista de espera',exact:true}).waitFor()
      await photo(page,'lista-espera')
      await page.getByRole('textbox',{name:'Nombre',exact:true}).fill('Clara Vidal')
      await page.getByRole('textbox',{name:'Teléfono',exact:true}).fill(size==='movil'?'+34612345684':'+34612345683')
      await page.getByRole('button',{name:'Apuntarme',exact:true}).click()
      await page.getByRole('heading',{name:'Estás en la lista de espera',exact:true}).waitFor()
      await photo(page,'lista-inscrita')
      await open(page,routes.offer,'Se ha liberado una mesa')
      await photo(page,'oferta')
      await open(page,routes.expired,'Se ha liberado una mesa')
      await page.getByRole('button',{name:'Aceptar la mesa',exact:true}).click()
      await page.getByRole('alert').waitFor()
      assert.equal(await page.getByRole('button',{name:'Aceptar la mesa',exact:true}).count(),0)
      await photo(page,'oferta-caducada')
      checks.push(`${size}: inscripción en lista y oferta caducada sin acción de aceptar`)

      await open(page,`/r/${routes.slug}/reserva/CRAR22`)
      await page.getByRole('heading',{level:1}).waitFor()
      await photo(page,'enlace-incompleto')
      await open(page,'/r/restaurante-que-no-existe','No encontramos este restaurante')
      await photo(page,'no-disponible')
      await open(page,`/widget/${routes.slug}`,'Personas')
      await photo(page,'widget')
      // Los idiomas se cambian sin perder los controles ni salir de la página.
      await page.getByRole('radio',{name:'Català',exact:true}).click()
      await page.getByRole('heading',{name:'Persones',exact:true}).waitFor()
      await photo(page,'widget-ca')
      assert.equal(await page.locator('html').getAttribute('lang'),'ca')
      await page.getByRole('radio',{name:'English',exact:true}).click()
      await page.getByRole('heading',{name:'Guests',exact:true}).waitFor()
      await photo(page,'widget-en')
      assert.equal(await page.locator('html').getAttribute('lang'),'en')
      checks.push(`${size}: idiomas es, ca y en; estados y widget sin desborde`)

      // Página anfitriona local servida por Playwright, sin añadir una ruta al producto.
      const host=base+'/z4-widget-host'
      await page.route(host,route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html lang="es"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Ejemplo local del widget</title><body style="margin:0;padding:24px;background:#131209;color:#f4f1ea;font-family:system-ui"><h1 style="font-size:24px">Taberna Lumbre</h1><p>Ejemplo local del widget de reservas</p><script src="${base}/widget.js" data-llenamos-slug="${routes.slug}" data-lang="es" data-color="#8fc7a0"></script></body></html>`}))
      await page.goto(host)
      const trigger=page.getByRole('button',{name:'Reservar mesa',exact:true})
      await trigger.waitFor()
      assert.equal(await trigger.evaluate(el=>el.getBoundingClientRect().height),48)
      if(size==='escritorio') {
        await trigger.click()
        await page.frameLocator('iframe').getByRole('heading',{name:'Personas',exact:true}).waitFor()
        await photo(page,'widget-modal')
        await page.keyboard.press('Escape')
        assert.equal(await trigger.evaluate(el=>el===document.activeElement),true)
      } else {
        const popup=page.waitForEvent('popup')
        await trigger.click()
        const child=await popup
        await child.getByRole('heading',{name:'Personas',exact:true}).waitFor()
        await photo(child,'widget-ventana')
        await child.close()
      }
      await page.unroute(host)
      await page.route(host,route=>route.fulfill({contentType:'text/html',body:`<!doctype html><html lang="es"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Ejemplo local del widget incrustado</title><body style="margin:0;padding:16px;background:#131209;color:#f4f1ea;font-family:system-ui"><h1 style="font-size:24px">Ejemplo local del widget</h1><script src="${base}/widget.js" data-llenamos-slug="${routes.slug}" data-mode="incrustado"></script></body></html>`}))
      await page.goto(host)
      await page.frameLocator('iframe').getByRole('heading',{name:'Personas',exact:true}).waitFor()
      await page.waitForTimeout(700)
      assert.ok(await page.locator('iframe').evaluate(el=>el.getBoundingClientRect().height > 640))
      assert.ok(await page.frameLocator('iframe').locator('html').evaluate(el=>el.scrollWidth<=el.clientWidth), 'El iframe no desborda')
      await photo(page,'widget-incrustado')
      checks.push(`${size}: widget.js abre ${size==='movil'?'página completa':'modal y devuelve el foco'}; iframe incrustado ajusta su altura`)
      await context.close()
    }
    currentSize='movil'
    const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,timezoneId:'Europe/Madrid'})
    const p=await mobile.newPage()
    await open(p,routes.offer,'Se ha liberado una mesa')
    await p.getByRole('button',{name:'Aceptar la mesa',exact:true}).click()
    await p.waitForURL('**/reserva/**')
    await p.getByRole('heading',{name:'Tienes mesa, Clara',exact:true}).waitFor()
    await photo(p,'oferta-aceptada')
    checks.push('Oferta real: cancelar libera mesa, mensaje capturado contiene enlace, aceptar crea reserva y abre gestión')
    await open(p,routes.pending,'Reserva recibida, Clara')
    await p.getByRole('button',{name:'Confirmar asistencia',exact:true}).click()
    await p.getByRole('heading',{name:'Tienes mesa, Clara',exact:true}).waitFor()
    checks.push('Confirmar asistencia desde una reserva pendiente conserva la acción del servidor')
    await open(p,`/widget/${routes.slug}`,'Personas')
    await p.locator('#sec-dia').locator('..').getByRole('radio').nth(1).click()
    await p.waitForFunction(() => document.querySelector('#sec-hora')?.parentElement?.querySelector('button:not(:disabled)'))
    await p.locator('#sec-hora').locator('..').locator('button:not(:disabled)').first().click()
    await details(p,'+34612345689','widget-datos-errores')
    await p.getByRole('button',{name:'Confirmar reserva',exact:true}).click()
    await p.waitForURL('**/reserva/**')
    assert.equal(new URL(p.url()).searchParams.get('embed'),'1')
    await p.getByRole('heading',{name:'Tienes mesa, Clara',exact:true}).waitFor()
    await photo(p,'widget-confirmada')
    checks.push('Reserva real desde widget conserva la navegación incrustada hasta la confirmación')
    await mobile.close()

    for(const role of ['propietario','encargado','camarero']) {
      currentSize='escritorio'
      const context=await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:2,timezoneId:'Europe/Madrid'})
      const page=await context.newPage()
      await page.goto(base+'/entrar')
      await page.getByRole('button',{name:new RegExp(`Entrar como ${role}`)}).first().click()
      await page.waitForURL('**/panel')
      await page.goto(base+'/panel/reservas')
      await page.getByRole('button',{name:'Buscar o ir a (Control K)',exact:true}).waitFor()
      await page.getByText('Pau Serra',{exact:true}).first().waitFor()
      assert.equal(await page.getByRole('button',{name:/Nueva reserva/}).count(),1)
      await page.getByRole('button',{name:/Nueva reserva/}).click()
      await page.getByRole('dialog').waitFor()
      await page.keyboard.press('Escape')
      if(role!=='camarero') {
        await page.goto(base+'/panel/muestra')
        await page.getByRole('heading',{name:'Ficha de una reserva pública',exact:true}).scrollIntoViewIfNeeded()
        if(role==='propietario') await photo(page,'muestra')
      }
      await page.goto(base+routes.confirmed)
      await page.getByRole('heading',{name:'Tienes mesa, Clara',exact:true}).waitFor()
      await context.close()
      checks.push(`${role}: acceso por /entrar, lectura de reservas y nueva reserva disponibles; enlace público funciona con sesión`)
    }
    currentSize='tableta'
    const tablet=await browser.newContext({viewport:{width:1180,height:820},deviceScaleFactor:2,timezoneId:'Europe/Madrid'})
    const page=await tablet.newPage()
    await booking(page,'taberna-lumbre')
    await page.evaluate(()=>window.scrollTo(0,0))
    await photo(page,'reservar')
    await tablet.close()
    assert.deepEqual(errors,[])
    fs.writeFileSync(path.join(__dirname,'comprobaciones.json'),JSON.stringify({checks,errors,screenshots},null,2)+'\n')
    console.log(`${checks.length} comprobaciones, ${screenshots.length} capturas a 2x, sin errores de página.`)
  } finally { await browser.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
