// Capturas y comprobaciones reales contra la fila 1. Ejecutar desde la raíz del worktree.
// Playwright se resuelve del entorno, sin añadir dependencias al proyecto.
const assert = require('node:assert/strict')
const path = require('node:path')
const { chromium } = require('playwright')

const base = 'http://localhost:3011'
const instante = new Date(process.env.LLENAMOS_CAPTURA_INSTANTE || '2026-11-09T21:12:00+01:00')
const fallos = []
const comprobado = []
const pausa = (page) => page.waitForTimeout(250)
const vista = (page, nombre) => page.locator('[aria-label="Vista"]').getByRole('radio', { name: nombre, exact: true })

async function foto(page, nombre, fullPage = false) {
  // Se oculta únicamente el indicador de desarrollo de Next, ajeno al producto.
  await page.addStyleTag({ content: 'nextjs-portal { display: none; }' })
  await page.evaluate(() => document.fonts.ready)
  await pausa(page)
  await page.screenshot({ path: path.join(__dirname, `${nombre}.png`), fullPage, animations: 'disabled' })
}

async function abrir(page, ruta) {
  await page.goto(`${base}${ruta}`)
  await page.getByRole('button', { name: 'Buscar o ir a (Control K)' }).waitFor()
}

async function main() {
  const browser = await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH
    ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH }
    : {})
  try {
    const desktop = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, timezoneId: 'Europe/Madrid' })
    desktop.on('page', (page) => page.on('pageerror', (error) => fallos.push(error.message)))
    const page = await desktop.newPage()
    await page.goto(`${base}/entrar`)
    await page.getByRole('button', { name: /Entrar como propietario/ }).click()
    await page.waitForURL('**/panel')
    await page.clock.setFixedTime(instante)
    await abrir(page, '/panel/reservas')
    await page.locator('[aria-label="Vista"]').waitFor()
    await vista(page, 'Lista').click()
    await foto(page, 'reservas-lista')

    // Primer toque elige, segundo abre. La mesa de la reserva queda resaltada.
    const fila = page.locator('[data-reserva-fila]').filter({ hasText: 'Pau Serra' }).first()
    await fila.click()
    await page.getByRole('region', { name: /Reserva elegida: Pau Serra/ }).waitFor()
    assert.equal(await fila.getAttribute('aria-pressed'), 'true')
    assert.ok(await page.locator('[data-elegida]').count() > 0)
    await fila.click()
    await page.getByRole('dialog').waitFor()
    await pausa(page)
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    comprobado.push('Lista: selección, mesa resaltada y apertura del detalle al segundo toque')

    await page.evaluate(() => window.scrollTo(0, 0))
    await vista(page, 'Tiempo').click()
    await page.getByRole('region', { name: 'Línea de tiempo de las reservas por mesa' }).waitFor()
    await foto(page, 'reservas-tiempo')
    await page.reload()
    await page.getByRole('region', { name: 'Línea de tiempo de las reservas por mesa' }).waitFor()
    const bloque = page.getByRole('button', { name: /Abrir la reserva de Pau Serra/ }).first()
    await bloque.click()
    await page.getByRole('dialog').waitFor()
    await pausa(page)
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await page.locator('[aria-label="Turno"]').getByRole('radio', { name: 'Todo el día', exact: true }).click()
    const tiempo = page.getByRole('region', { name: 'Línea de tiempo de las reservas por mesa' })
    await tiempo.evaluate((el) => { el.scrollLeft = 0 })
    await tiempo.focus()
    const diaAntes = await page.getByRole('button', { name: /^Día de las reservas:/ }).getAttribute('aria-label')
    await page.keyboard.press('ArrowRight')
    await pausa(page)
    assert.ok(await tiempo.evaluate((el) => el.scrollLeft > 0), 'La flecha desplaza el tiempo')
    assert.equal(await page.getByRole('button', { name: /^Día de las reservas:/ }).getAttribute('aria-label'), diaAntes)
    await page.locator('[aria-label="Turno"]').getByRole('radio', { name: 'Cena', exact: true }).click()
    comprobado.push('Tiempo: persistencia, apertura del detalle y flechas para desplazar sin cambiar de día')

    await page.keyboard.press('Control+k')
    const paleta = page.getByRole('dialog', { name: 'Buscar o ir a' })
    await paleta.getByRole('combobox').fill('pau')
    await paleta.getByRole('option', { name: /Pau Serra/ }).first().waitFor()
    await foto(page, 'paleta')
    await page.keyboard.press('Enter')
    await paleta.waitFor({ state: 'hidden' })
    await page.getByRole('dialog').filter({ hasNot: page.locator('[cmdk-root]') }).waitFor()
    await pausa(page)
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    comprobado.push('Paleta: buscar una reserva y abrir su detalle')

    await page.keyboard.press('?')
    await page.getByRole('dialog', { name: 'Atajos de teclado' }).waitFor()
    const ayuda = await page.getByRole('dialog', { name: 'Atajos de teclado' }).boundingBox()
    assert.ok(ayuda.y >= 0 && ayuda.y + ayuda.height <= 900, 'La ayuda cabe en la pantalla')
    await foto(page, 'atajos')
    await page.keyboard.press('Escape')
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await vista(page, 'Lista').click()
    const buscar = page.getByRole('searchbox', { name: 'Buscar reserva' })
    await buscar.fill('nvt')
    assert.equal(await page.getByRole('dialog').count(), 0)
    assert.equal(await vista(page, 'Lista').getAttribute('aria-checked'), 'true')
    await buscar.press('Escape')
    await page.keyboard.press('n')
    await page.getByRole('dialog').waitFor()
    await page.keyboard.press('v')
    await page.keyboard.press('Escape')
    assert.equal(await vista(page, 'Lista').getAttribute('aria-checked'), 'true')
    comprobado.push('Atajos: ayuda, nueva reserva y teclas sueltas desactivadas al escribir o con ventana')

    await page.keyboard.press('g')
    await page.keyboard.press('s')
    await page.waitForURL('**/panel/sala')
    await page.getByRole('button', { name: /^Mesa S2,/ }).click()
    await foto(page, 'sala')
    comprobado.push('Navegación G S y ficha de una mesa redonda en Sala')

    const state = await desktop.storageState({ indexedDB: true })
    const tablet = await browser.newContext({ viewport: { width: 1180, height: 820 }, deviceScaleFactor: 2, timezoneId: 'Europe/Madrid', storageState: state, hasTouch: true })
    const tab = await tablet.newPage()
    tab.on('pageerror', (error) => fallos.push(error.message))
    await tab.clock.setFixedTime(instante)
    await abrir(tab, '/panel/reservas')
    await vista(tab, 'Lista').click()
    await tab.getByRole('searchbox', { name: 'Buscar reserva' }).fill('sin coincidencias')
    await tab.getByRole('button', { name: /^Mesa S2,/ }).click()
    assert.equal(await tab.getByRole('searchbox', { name: 'Buscar reserva' }).inputValue(), '')
    assert.ok(await tab.locator('[data-reserva-fila][aria-pressed="true"]').count() > 0)
    await tab.locator('[aria-label="Zona"]').getByRole('radio', { name: 'Terraza', exact: true }).click()
    await tab.locator('[data-reserva-fila]').filter({ hasText: 'Julia Cano' }).first().click()
    await tab.getByRole('region', { name: 'Plano de la zona Sala' }).waitFor()
    const seleccion = tab.getByRole('region', { name: /Reserva elegida:/ })
    await seleccion.waitFor()
    await tab.waitForTimeout(800)
    const elegida = await seleccion.getAttribute('aria-label')
    assert.ok(await tab.locator('[data-reserva-fila][aria-pressed="true"]').count() > 0)
    const alturas = await seleccion.locator('button').evaluateAll((buttons) => buttons.map((b) => b.getBoundingClientRect().height))
    assert.ok(alturas.every((h) => h >= 48))
    await foto(tab, 'tableta')
    comprobado.push(`Tableta: mesa muestra su fila oculta, selección cambia de zona y acciones de 48 px (${elegida})`)

    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, timezoneId: 'Europe/Madrid', storageState: state, hasTouch: true, isMobile: true })
    const movil = await mobile.newPage()
    movil.on('pageerror', (error) => fallos.push(error.message))
    await movil.clock.setFixedTime(instante)
    await abrir(movil, '/panel/reservas')
    await vista(movil, 'Lista').click()
    const dia = await movil.getByRole('button', { name: /^Día de las reservas:/ }).boundingBox()
    const turno = await movil.locator('[aria-label="Turno"]').boundingBox()
    assert.ok(Math.abs(dia.y - turno.y) < 10, 'Día y turno deben quedar en la misma línea a 390 px')
    assert.ok(await movil.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sin desbordamiento horizontal')
    await foto(movil, 'movil')
    await movil.locator('[data-reserva-fila]').first().click()
    await movil.getByRole('dialog').waitFor()
    await movil.keyboard.press('Escape')
    await vista(movil, 'Plano').click()
    await foto(movil, 'movil-plano')
    comprobado.push('Móvil: controles en una línea, sin desbordamiento, detalle al primer toque y conmutador al plano')

    await abrir(page, '/panel/muestra')
    await page.getByRole('heading', { name: 'Capas de la sala cálida' }).scrollIntoViewIfNeeded()
    await foto(page, 'muestra', true)
    comprobado.push('Muestra: piezas nuevas disponibles')
    assert.deepEqual(fallos, [], 'Sin errores de ejecución del navegador')
    console.log(JSON.stringify({ instante: instante.toISOString(), escala: 2, comprobado }, null, 2))
  } finally {
    await browser.close()
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
