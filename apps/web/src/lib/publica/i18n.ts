export function shiftLabel(name: string, lang: Language): string {
  const key = name
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
  return SHIFT_NAMES[key]?.[lang] ?? name
}
