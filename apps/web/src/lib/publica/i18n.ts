export const DICTIONARIES: Record<Language, Dictionary> = { es, ca, en }

/** Nombre de cada idioma en su propio idioma, para el selector. */
export const LANGUAGE_NAMES: Record<Language, string> = { es: "Castellano", ca: "Català", en: "English" }

/** Etiqueta de idioma para Intl y para el atributo lang. */
export const INTL_LOCALE: Record<Language, string> = { es: "es-ES", ca: "ca-ES", en: "en-GB" }

export type Vars = Record<string, string | number>
export type Translate = (key: TextKey, vars?: Vars) => string

/** Sustituye `{variable}`. Una variable que falta se deja tal cual para que se vea en las pruebas. */
export function interpolate(text: string, vars: Vars = {}): string {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

export function translator(lang: Language): Translate {
  const dict = DICTIONARIES[lang]
  return (key, vars) => interpolate(dict[key], vars)
}

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && (LANGUAGES as readonly string[]).includes(value)
}

/** Idioma de la página: el que pide el enlace (`?lang=ca`) si es válido; si no, el del restaurante. */
export function pickLanguage(requested: string | string[] | undefined | null, fallback: Language): Language {
  const value = Array.isArray(requested) ? requested[0] : requested
  const short = value?.trim().toLowerCase().slice(0, 2)
  return isLanguage(short) ? short : fallback
}

/** «1 persona», «4 personas». */
export function peopleLabel(t: Translate, n: number): string {
  return t(n === 1 ? "peopleOne" : "peopleMany", { n })
}

